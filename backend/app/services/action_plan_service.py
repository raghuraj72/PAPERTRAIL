import csv
import io
import json
from typing import List, Dict, Optional, Any

from app.models.schemas import (
    Requirement,
    RequirementCategory,
    TaskStatus,
    Priority,
    TaskUpdateRequest,
    Workspace
)

class ActionPlanService:
    @staticmethod
    def update_task(
        workspace: Workspace,
        task_id: str,
        update: TaskUpdateRequest
    ) -> Optional[Requirement]:
        target_req = None
        # Check combined requirements
        for r in workspace.combined_requirements:
            if r.id == task_id:
                target_req = r
                break
                
        # Also check inside individual documents
        if not target_req:
            for doc in workspace.documents:
                for r in doc.requirements:
                    if r.id == task_id:
                        target_req = r
                        break
                if target_req:
                    break
                    
        if not target_req:
            return None
            
        if update.status is not None:
            target_req.status = update.status
        if update.personal_notes is not None:
            target_req.personal_notes = update.personal_notes
        if update.user_reminder is not None:
            target_req.user_reminder = update.user_reminder
        if update.priority is not None:
            target_req.priority = update.priority
            
        # Recompute workspace completion count
        completed = sum(1 for r in workspace.combined_requirements if r.status == TaskStatus.COMPLETED)
        workspace.action_plan_completed_count = completed
        workspace.action_plan_total_count = len(workspace.combined_requirements)
        
        return target_req

    @staticmethod
    def export_markdown(workspace: Workspace) -> str:
        lines = [
            f"# Action Plan: {workspace.name}",
            f"*Generated by PAPERTRAIL — The Clarity Engine*",
            f"**Progress**: {workspace.action_plan_completed_count} / {workspace.action_plan_total_count} tasks completed\n",
            "---"
        ]
        
        for category in RequirementCategory:
            cat_reqs = [r for r in workspace.combined_requirements if r.category == category]
            if not cat_reqs:
                continue
            lines.append(f"\n## {category.value}\n")
            for r in cat_reqs:
                check = "[x]" if r.status == TaskStatus.COMPLETED else "[ ]"
                mand = "(Mandatory)" if r.is_mandatory else "(Optional)"
                deadline_str = f" | Due: {r.deadline}" if r.deadline else ""
                lines.append(f"- {check} **{r.title}** {mand}{deadline_str}")
                lines.append(f"  - *Explanation*: {r.plain_language}")
                lines.append(f"  - *Source*: Page {r.citation.page_number} ({r.citation.section_heading}): \"{r.citation.exact_passage[:100]}...\"")
                if r.personal_notes:
                    lines.append(f"  - *Note*: {r.personal_notes}")
                if r.user_reminder:
                    lines.append(f"  - *Reminder*: {r.user_reminder}")
                    
        return "\n".join(lines)

    @staticmethod
    def export_csv(workspace: Workspace) -> str:
        output = io.StringIO()
        writer = csv.writer(output)
        writer.writerow([
            "Task ID", "Category", "Title", "Mandatory", "Status",
            "Priority", "Deadline", "Plain Language", "Source Page", "Source Section", "Notes"
        ])
        for r in workspace.combined_requirements:
            writer.writerow([
                r.id,
                r.category.value,
                r.title,
                "Yes" if r.is_mandatory else "No",
                r.status.value,
                r.priority.value,
                r.deadline or "",
                r.plain_language,
                r.citation.page_number,
                r.citation.section_heading,
                r.personal_notes or ""
            ])
        return output.getvalue()

    @staticmethod
    def export_json(workspace: Workspace) -> str:
        data = {
            "workspace_id": workspace.id,
            "workspace_name": workspace.name,
            "progress": {
                "completed": workspace.action_plan_completed_count,
                "total": workspace.action_plan_total_count
            },
            "tasks": [r.model_dump() for r in workspace.combined_requirements]
        }
        return json.dumps(data, indent=2)
